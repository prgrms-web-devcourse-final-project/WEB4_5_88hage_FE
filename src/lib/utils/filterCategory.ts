export const filterContentCategory = (category:string) => {
    if(category === 'THEATER'){
        return '연극'
    }
    if(category === 'DANCE'){
        return '댄스'
    }
    if(category === 'POP_DANC'){
        return '팝댄스'
    }
    if(category === 'CLASSIC'){
        return '클래식'
    }
    if(category === 'GUKAK'){
        return '국악'
    }
    if(category === 'POP_MUSIC'){
        return '팝음악'
    }
    if(category === 'MIX'){
        return '혼합'
    }
    if(category === 'MAGIC'){
        return '마술'
    }
    if(category === 'MUSICAL'){
        return '뮤지컬'
    }
    if(category === 'TOUR'){
        return '투어'
    }
    if(category === 'CULTURE'){
        return '문화'
    }
    if(category === 'SPORTS'){
        return '스포츠'
    }
}
export const filterGatheringCategory = (category:string) => {
    if(category === 'GAME'){
        return '게임'
    }
    if(category === 'FOOD'){
        return '음식'
    }
    if(category === 'TRAVEL'){
        return '여행'
    }
    if(category === 'ART'){
        return '예술'
    }
    if(category === 'CULTURE'){
        return '문화'
    }
    if(category === 'STUDY'){
        return '자기개발'
    }
    if(category === 'SPORT'){
        return '운동'
    }
}
